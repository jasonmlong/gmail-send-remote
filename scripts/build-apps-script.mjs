// Bundles the renderer (src/core, runtime-agnostic) into a single Apps Script
// file, apps-script/GmailSendCore.js, exposed as the global `GmailSendCore`.
import { build } from 'esbuild';
import { mkdirSync } from 'node:fs';

mkdirSync('apps-script', { recursive: true });
await build({
  entryPoints: ['src/core/browser.ts'],
  bundle: true,
  format: 'iife',
  globalName: 'GmailSendCore',
  target: 'es2020',
  platform: 'neutral',
  outfile: 'apps-script/GmailSendCore.js',
  banner: {
    js: '// Generated by scripts/build-apps-script.mjs from src/core. Do not edit by hand; run `npm run build:apps-script`.\n// Paste into the Apps Script project as GmailSendCore.gs next to Api.gs, GmailAdapter.gs, Drafting.gs and Setup.gs.',
  },
  logLevel: 'info',
});
